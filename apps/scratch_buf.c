#include "scratch_buf.h"

#define SCRATCH_BUFFER_SIZE 0x800000 /* 8 MiB, matches the old plugin buffer */

static unsigned char scratch_buffer[SCRATCH_BUFFER_SIZE];

void *scratch_buffer_get(size_t *size)
{
    if (size)
        *size = SCRATCH_BUFFER_SIZE;
    return scratch_buffer;
}
